// books.js의 항목에 전용 대사와 외형을 얹는다. 없는 책은 1층 템플릿으로 자동 처리된다.
export function applyVoices(books) {
  for (const b of books) {
    const v = VOICES[b.id];
    if (!v) continue;
    b.tags = v.tags;
    b.hair = v.hair;
    b.barbs = v.barbs || {};
    b.defends = v.defends || {};
    b.rivalBarbs = v.rival || {};
  }
  return books;
}
